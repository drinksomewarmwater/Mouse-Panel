def sign_session(username):
    expiry = int(time.time()) + SESSION_DAYS * 86400
    payload = "%s.%d" % (username, expiry)
    sig = hmac.new(session_secret().encode(), payload.encode(), hashlib.sha256).hexdigest()
    raw = "%s.%s" % (payload, sig)
    return base64.urlsafe_b64encode(raw.encode()).decode(), expiry


def verify_session(cookie_value):
    try:
        raw = base64.urlsafe_b64decode(cookie_value.encode()).decode()
        username, expiry, sig = raw.rsplit(".", 2)
        if int(expiry) < int(time.time()):
            return None
        payload = "%s.%s" % (username, expiry)
        want = hmac.new(session_secret().encode(), payload.encode(), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(want, sig):
            return None
        u = get_user(username)
        if not u:
            return None
        return u
    except Exception:
        return None


def parse_cookies(handler):
    raw = handler.headers.get("Cookie", "")
    out = {}
    for part in raw.split(";"):
        if "=" in part:
            k, v = part.strip().split("=", 1)
            out[k] = v
    return out


