def remote_server(sid):
    """The servers.json entry for a remote server id (None if not found)."""
    for s in load_servers():
        if s.get("id") == sid and s.get("type") == "remote":
            return s
    return None


def first_remote():
    for s in load_servers():
        if s.get("type") == "remote":
            return s
    return None


def remote_ssh(server, remote_cmd, timeout=30):
    cmd = ("ssh -i %s -o StrictHostKeyChecking=accept-new "
           "-o ConnectTimeout=15 -o BatchMode=yes -p %s root@%s %s"
           % (PANEL_SSH_KEY, server.get("port") or 22, server.get("host"),
              remote_cmd))
    return run(cmd, timeout=timeout)


def remote_read(server):
    rc, out, err = remote_ssh(server, "python3 %s read" % AGENT_SCRIPT)
    if rc != 0:
        raise RuntimeError("remote read failed: %s" % (err or out))
    d = json.loads(out)
    if d.get("ok") is False:
        raise RuntimeError("remote read failed: %s" % d.get("error"))
    return d


def remote_vless_link(server, d):
    """Build the remote VLESS link from the agent's read output."""
    domain = d.get("domain") or server.get("host", "")
    port = d.get("vless_port") or 443
    name = server.get("name") or "远程"
    if d.get("vless_security") == "reality":
        r = d.get("reality") or {}
        return ("vless://%s@%s:%d?security=reality&encryption=none&pbk=%s"
                "&fp=%s&type=tcp&flow=xtls-rprx-vision&sni=%s&sid=%s"
                "#【推荐】%s-Vless"
                % (d["vless_uuid"], domain, port, r.get("pbk", ""),
                   r.get("fp", "chrome"), r.get("sni", "www.apple.com"),
                   r.get("sid", ""), name))
    return ("vless://%s@%s:%d?encryption=none&security=tls&sni=%s&type=tcp"
            "#【推荐】%s-Vless"
            % (d["vless_uuid"], domain, port, domain, name))


