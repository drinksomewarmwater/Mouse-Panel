def sync_vless_users_bg():
    """Run the VLESS sync in a background thread (same reason as HY2:
    the sync SSHes to remote servers and reloads sing-box, which takes
    seconds; doing it inline blocked the HTTP response)."""
    def _run():
        try:
            with LOCK:
                sync_vless_users()
        except Exception as e:
            log.error("bg vless sync failed: %s", e)
    threading.Thread(target=_run, daemon=True).start()


def sync_hy2_users_bg():
    """Run the HY2 sync in a background thread.

    The sync SSHes to every remote server and restarts hysteria-server
    on each box,
    which takes several seconds. Doing it inline blocked the HTTP response
    for so long that clients disconnected (BrokenPipeError) and reported a
    false failure even though the DB change had already succeeded.
    The DB is the source of truth for what the panel shows; the Hysteria
    configs catch up a few seconds later. Failures are logged.
    """
    def _run():
        try:
            with LOCK:
                sync_hy2_users()
        except Exception as e:
            log.error("bg hy2 sync failed: %s", e)
    threading.Thread(target=_run, daemon=True).start()

# --- rotation ---

def rotate_vless():
    new_uuid = str(uuid.uuid4())
    run("cp %s %s.bak-rotate" % (SINGBOX_CFG, SINGBOX_CFG))
    try:
        with open(SINGBOX_CFG) as f:
            cfg = json.load(f)
        found = False
        for ib in cfg.get("inbounds", []):
            if ib.get("type") == "vless" and ib.get("tag") == "vless-in":
                users = ib.get("users", [])
                if users:
                    users[0]["uuid"] = new_uuid
                    found = True
        if not found:
            raise RuntimeError("vless inbound/user not found in sing-box config")
        with open(SINGBOX_CFG, "w") as f:
            json.dump(cfg, f, indent=2)
            f.write("\n")
        run("systemctl restart sing-box")
        time.sleep(2)
        if not service_active("sing-box") or not tcp_listening(443):
            raise RuntimeError("sing-box did not come back up after restart")
    except Exception:
        run("cp %s.bak-rotate %s" % (SINGBOX_CFG, SINGBOX_CFG))
        run("systemctl restart sing-box")
        raise
    links = load_links()
    old = links["vless"]
    new_link = re.sub(r"(vless://)[^@]+(@)", r"\g<1>" + new_uuid + r"\g<2>", old, count=1)
    links["vless"] = new_link
    save_links(links)
    # The admin's VLESS credential changed, so the old subscription URL
    # must stop working. A token-write failure must not mask a rotation
    # that already succeeded, so it is only logged.
    try:
        regenerate_sub_token("admin")
    except Exception as e:
        log.error("rotate_vless: sub_token regen failed: %s", e)
    return new_link


def rotate_admin_hy2():
    """Rotate the admin's unified HY2 password AND every set-up user's HY2
    password, then disable all non-admin users (reason 'rotated') and push
    the new set to both servers (restarts hysteria-server on both). Only the
    admin keeps access; a disabled user gets their new link back once the
    admin re-enables them. Returns (admin_new_pw, users_rotated_count).
    Users who never finished first-time setup (pw_set=0) have no working
    link yet, so they are left untouched."""
    new_pw = secrets.token_hex(16)
    conn = db()
    conn.execute("UPDATE users SET hy2_password=?, sub_token=?"
                 " WHERE username='admin'",
                 (new_pw, secrets.token_hex(16)))
    users = conn.execute(
        "SELECT username FROM users WHERE role='user' AND pw_set=1"
    ).fetchall()
    count = 0
    for (username,) in users:
        user_pw = secrets.token_hex(16)
        conn.execute(
            "UPDATE users SET hy2_password=?, enabled=0, disabled_reason='rotated',"
            " sub_token=? WHERE username=?",
            (user_pw, secrets.token_hex(16), username),
        )
        count += 1
    conn.commit()
    conn.close()
    sync_hy2_users_bg()
    sync_vless_users_bg()
    return new_pw, count


