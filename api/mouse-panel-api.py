def _parse_ts(s):
    """Parse an ISO-ish datetime (with or without seconds). Returns a
    naive datetime in server local time, or None."""
    s = (s or "").strip()
    for fmt in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M",
                "%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M"):
        try:
            return datetime.strptime(s[:19], fmt)
        except ValueError:
            continue
    return None


def export_logs(all_flag, from_s, to_s):
    """Read the current log file plus rotated backups (oldest to newest)
    and return the lines inside [from, to] as bytes. Each bound is
    optional (unbounded that end); all_flag returns everything. Lines
    without a parseable timestamp (e.g. tracebacks) are kept — they
    belong to the previous entry."""
    files = []
    for i in range(LOG_BACKUP_COUNT, 0, -1):
        p = "%s.%d" % (LOG_PATH, i)
        if os.path.exists(p):
            files.append(p)
    if os.path.exists(LOG_PATH):
        files.append(LOG_PATH)
    from_dt = None
    to_dt = None
    if not all_flag:
        if from_s:
            from_dt = _parse_ts(from_s)
        if to_s:
            to_dt = _parse_ts(to_s)
            # A minute-precision "to" means the end of that minute.
            if to_dt and len(to_s.strip()) <= 16:
                to_dt = to_dt + timedelta(seconds=59)
    out = []
    for fp in files:
        try:
            with open(fp, "rb") as f:
                data = f.read()
        except OSError:
            continue
        for line in data.split(b"\n"):
            if not line:
                continue
            if not all_flag and (from_dt or to_dt):
                ts = _parse_ts(line[:19].decode("utf-8", "ignore"))
                if ts is not None:
                    if from_dt and ts < from_dt:
                        continue
                    if to_dt and ts > to_dt:
                        continue
            out.append(line)
    return b"\n".join(out) + (b"\n" if out else b"")


