def ensure_user_columns():
    """Add the VLESS / per-server-limit / password-permission columns if
    missing (idempotent)."""
    global _COLUMNS_ENSURED
    if _COLUMNS_ENSURED:
        return
    conn = db()
    cols = [r[1] for r in conn.execute("PRAGMA table_info(users)")]
    for col, ddl in [
        ("vless_uuid", "ALTER TABLE users ADD COLUMN vless_uuid TEXT"),
        ("vless_port", "ALTER TABLE users ADD COLUMN vless_port INTEGER"),
        ("limits_json", "ALTER TABLE users ADD COLUMN limits_json TEXT"),
        ("disabled_json", "ALTER TABLE users ADD COLUMN disabled_json TEXT"),
        ("allow_pw_change", "ALTER TABLE users ADD COLUMN allow_pw_change INTEGER NOT NULL DEFAULT 1"),
    ]:
        if col not in cols:
            conn.execute(ddl)
    conn.commit()
    conn.close()
    _COLUMNS_ENSURED = True


def parse_limits(row):
    """Per-server limits in GB: {"local": 200, "d1": 300}, None = unlimited.
    Falls back to the legacy single limit_gb (same value for every server)."""
    try:
        lj = json.loads(row["limits_json"]) if row.get("limits_json") else {}
    except Exception:
        lj = {}
    if not isinstance(lj, dict):
        lj = {}
    if not lj and row.get("limit_gb") is not None:
        lj = {sid: row["limit_gb"] for sid in all_server_ids()}
    out = {}
    for sid in all_server_ids():
        v = lj.get(sid)
        try:
            out[sid] = float(v) if v is not None else None
        except (TypeError, ValueError):
            out[sid] = None
    return out


def parse_disabled(row):
    """Per-server disabled reasons: {"local": "over_limit", "d1": None}."""
    try:
        dj = json.loads(row["disabled_json"]) if row.get("disabled_json") else {}
    except Exception:
        dj = {}
    if not isinstance(dj, dict):
        dj = {}
    return {sid: dj.get(sid) for sid in all_server_ids()}


def parse_limits_body(body):
    """Per-server limits from a request body. Accepts {"limits": {...}} or
    the legacy {"limit_gb": X} (same value for every server).
    Returns {server_id: float|None}. Raises ValueError."""
    limits = body.get("limits")
    if isinstance(limits, dict):
        out = {}
        for sid in all_server_ids():
            v = limits.get(sid)
            if v is None or v == "":
                out[sid] = None
            else:
                v = float(v)
                if v <= 0:
                    raise ValueError("月流量上限须为正数，或留空表示不限")
                out[sid] = v
        return out
    limit = body.get("limit_gb")
    if limit is None or limit == "":
        return {sid: None for sid in all_server_ids()}
    limit = float(limit)
    if limit <= 0:
        raise ValueError("月流量上限须为正数，或留空表示不限")
    return {sid: limit for sid in all_server_ids()}


