def user_usage(username):
    """Monthly + today HY2 traffic for one user: combined totals plus a
    per-server breakdown (servers: {id: {month_*, today_*}})."""
    from datetime import datetime, timedelta, timezone

    now_bj = datetime.now(timezone.utc) + timedelta(hours=8)
    month = now_bj.strftime("%Y-%m")
    today = now_bj.strftime("%Y-%m-%d")
    conn = db()
    m = conn.execute(
        "SELECT COALESCE(SUM(tx),0) AS tx, COALESCE(SUM(rx),0) AS rx FROM usage_daily "
        "WHERE username=? AND substr(date,1,7)=?",
        (username, month),
    ).fetchone()
    t = conn.execute(
        "SELECT COALESCE(SUM(tx),0) AS tx, COALESCE(SUM(rx),0) AS rx FROM usage_daily "
        "WHERE username=? AND date=?",
        (username, today),
    ).fetchone()
    servers = {}
    for sid in all_server_ids():
        sm = conn.execute(
            "SELECT COALESCE(SUM(tx),0) AS tx, COALESCE(SUM(rx),0) AS rx FROM usage_daily "
            "WHERE username=? AND server=? AND substr(date,1,7)=?",
            (username, sid, month),
        ).fetchone()
        st = conn.execute(
            "SELECT COALESCE(SUM(tx),0) AS tx, COALESCE(SUM(rx),0) AS rx FROM usage_daily "
            "WHERE username=? AND server=? AND date=?",
            (username, sid, today),
        ).fetchone()
        servers[sid] = {
            "month_tx": sm["tx"], "month_rx": sm["rx"],
            "month_total": sm["tx"] + sm["rx"],
            "today_tx": st["tx"], "today_rx": st["rx"],
            "today_total": st["tx"] + st["rx"],
        }
    conn.close()
    return {
        "month": month,
        "month_tx": m["tx"],
        "month_rx": m["rx"],
        "month_total": m["tx"] + m["rx"],
        "today": today,
        "today_tx": t["tx"],
        "today_rx": t["rx"],
        "today_total": t["tx"] + t["rx"],
        "servers": servers,
    }


# --- sessions (signed cookie) ---

def sign_session(username):
    expiry = int(time.time()) + SESSION_DAYS * 86400
    payload = "%s.%d" % (username, expiry)
    sig = hmac.new(session_secret().encode(), payload.encode(), hashlib.sha256).hexdigest()
    raw = "%s.%s" % (payload, sig)
    return base64.urlsafe_b64encode(raw.encode()).decode(), expiry


def verify_session(cookie_value):
    try:
        raw = base64.urlsafe_b64decode(cookie_value.encode()).decode()
        username, expiry, sig = raw.rsplit(".", 2)
        if int(expiry) < int(time.time()):
            return None
        payload = "%s.%s" % (username, expiry)
        want = hmac.new(session_secret().encode(), payload.encode(), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(want, sig):
            return None
        u = get_user(username)
        if not u:
            return None
        return u
    except Exception:
        return None


def parse_cookies(handler):
    raw = handler.headers.get("Cookie", "")
    out = {}
    for part in raw.split(";"):
        if "=" in part:
            k, v = part.strip().split("=", 1)
            out[k] = v
    return out


