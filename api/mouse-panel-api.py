def ensure_db():
    """Create the user database (schema + session secret) on first run.

    A fresh install ships no users.db at all: the admin account is created
    later, on first open, via POST /api/admin/setup. The DB file is
    root-only (0600).
    """
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    try:
        conn.executescript(SCHEMA)
        row = conn.execute("SELECT value FROM meta WHERE key='session_secret'").fetchone()
        if not row:
            conn.execute(
                "INSERT INTO meta (key, value) VALUES ('session_secret', ?)",
                (secrets.token_hex(32),),
            )
        conn.commit()
    finally:
        conn.close()
    try:
        os.chmod(DB_PATH, 0o600)
    except OSError:
        pass
    # Column migrations (e.g. allow_pw_change) run here so every request
    # sees the current schema; the guard inside makes this a no-op after
    # the first run in each process.
    ensure_user_columns()


