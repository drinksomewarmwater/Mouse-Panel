class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        msg = fmt % args
        # Never log a subscription token: the request line would carry it.
        msg = re.sub(r"/sub/[0-9a-f]{32}", "/sub/<token>", msg)
        log.info("%s %s", self.client_address[0], msg)

    def _json(self, code, obj, set_cookie=None, clear_cookie=False):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        if set_cookie is not None:
            self.send_header(
                "Set-Cookie",
                "panel_session=%s; HttpOnly; Secure; SameSite=Lax; Max-Age=%d; Path=/"
                % (set_cookie, SESSION_DAYS * 86400),
            )
        if clear_cookie:
            self.send_header(
                "Set-Cookie",
                "panel_session=; HttpOnly; Secure; SameSite=Lax; Max-Age=0; Path=/",
            )
        self.end_headers()
        self.wfile.write(body)

    def _text(self, code, body):
        data = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _read_json(self):
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            n = 0
        if n <= 0:
            return {}
        raw = self.rfile.read(n)
        try:
            return json.loads(raw.decode())
        except Exception:
            return {}

    def _read_body(self, limit):
        """Raw request body bytes (None when missing / over the limit)."""
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            n = 0
        if n <= 0 or n > limit:
            return None
        return self.rfile.read(n)

    def _read_multipart(self):
        """Minimal multipart/form-data parser. Returns (parts, error) where
        parts is a list of {name, filename, content_type, data}."""
        ctype = self.headers.get("Content-Type", "")
        m = re.search(r"boundary=([^;]+)", ctype)
        if not m:
            return None, "missing boundary"
        boundary = m.group(1).strip().strip('"')
        raw = self._read_body(MUSIC_MAX_BYTES + 1024 * 1024)
        if raw is None:
            return None, "请求体缺失或过大"
        parts = []
        for chunk in raw.split(("--" + boundary).encode()):
            if not chunk or chunk in (b"--\r\n", b"--", b"\r\n"):
                continue
            if chunk.startswith(b"\r\n"):
                chunk = chunk[2:]
            if chunk.endswith(b"\r\n"):
                chunk = chunk[:-2]
            if chunk.endswith(b"--"):
                chunk = chunk[:-2]
            if b"\r\n\r\n" not in chunk:
                continue
            head, data = chunk.split(b"\r\n\r\n", 1)
            headers = {}
            for line in head.decode("utf-8", "ignore").split("\r\n"):
                if ":" in line:
                    k, v = line.split(":", 1)
                    headers[k.strip().lower()] = v.strip()
            disp = headers.get("content-disposition", "")
            nm = re.search(r'name="([^"]*)"', disp)
            fn = re.search(r'filename="([^"]*)"', disp)
            parts.append({
                "name": nm.group(1) if nm else "",
                "filename": fn.group(1) if fn else "",
                "content_type": headers.get("content-type", ""),
                "data": data,
            })
        return parts, None

