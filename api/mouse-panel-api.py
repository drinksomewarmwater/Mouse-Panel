def ensure_vless_for_user(username):
    """Give a user a VLESS UUID + port if they don't have one yet.
    Returns (uuid, port) or None if the user does not exist."""
    conn = db()
    row = conn.execute(
        "SELECT vless_uuid, vless_port FROM users WHERE username=?", (username,)
    ).fetchone()
    if row is None:
        conn.close()
        return None
    if row["vless_uuid"] and row["vless_port"]:
        conn.close()
        return row["vless_uuid"], row["vless_port"]
    u = str(uuid.uuid4())
    p = alloc_vless_port(conn)
    conn.execute(
        "UPDATE users SET vless_uuid=?, vless_port=? WHERE username=?",
        (u, p, username),
    )
    conn.commit()
    conn.close()
    return u, p


